package org.betonquest.betonquest.quest.placeholder.section;

/**
 * Selection mode for section placeholders.
 */
public enum SectionSelectionMode {

    /**
     * Select elements beginning with the first and ending with the last.
     */
    FIRST,
    /**
     * Select elements beginning with the last and ending with the first.
     */
    LAST,
    /**
     * Select elements randomly.
     */
    RANDOM
}
